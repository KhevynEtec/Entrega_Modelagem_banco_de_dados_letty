-- Atende: P1 (risco de perdas por vencimento no PDV); RN09 (alerta de validade; urgente em até 10 dias)
SELECT l.nm_loja, p.ds_produto, iv.qt_estoque_gondola, v.dt_visita, iv.dt_validade_encontrada,
       DATEDIFF(iv.dt_validade_encontrada, CURDATE()) AS dias_para_vencer,
       CASE WHEN DATEDIFF(iv.dt_validade_encontrada, CURDATE()) <= 10 THEN 'URGENTE' ELSE 'ATENCAO' END AS prioridade
FROM item_visita iv
JOIN visita v ON iv.id_visita = v.id_visita
JOIN loja l ON v.id_loja = l.id_loja
JOIN produto p ON iv.id_produto = p.id_produto
WHERE v.dt_visita >= DATE_SUB(CURDATE(), INTERVAL 30 DAY)
  AND iv.qt_estoque_gondola > 0
  AND iv.dt_validade_encontrada BETWEEN CURDATE() AND DATE_ADD(CURDATE(), INTERVAL 30 DAY)
ORDER BY dias_para_vencer, l.nm_loja;

-- G02 — Quais ocorrências de produtos vencidos/avariados existem por loja?
-- Atende: P1 (risco de perdas por vencimento no PDV)
SELECT l.nm_loja, p.ds_produto, vp.numero_lote, vp.quantidade_produto_vencido, vp.status_vencimento
FROM vencimento_prod vp
JOIN loja l ON vp.id_loja = l.id_loja
JOIN produto p ON vp.id_produto = p.id_produto;

-- G03 — Qual a rotina e o tempo médio de permanência de cada promotor nas lojas (últimos 90 dias)?
-- Atende: P2 (acompanhamento da promotoria); KPI tempo médio de permanência
SELECT pr.nm_promotor, pr.nm_empresa_terceirizada AS nm_empresa,
       COUNT(*) AS qt_visitas, COUNT(DISTINCT v.id_loja) AS qt_lojas,
       ROUND(AVG(TIME_TO_SEC(TIMEDIFF(v.hr_fim, v.hr_inicio))) / 60) AS min_medio_permanencia,
       MAX(v.dt_visita) AS ultima_visita
FROM visita v
JOIN promotor pr ON v.id_promotor = pr.id_promotor
WHERE v.dt_visita >= DATE_SUB(CURDATE(), INTERVAL 90 DAY)
GROUP BY pr.id_promotor, pr.nm_promotor, pr.nm_empresa_terceirizada
ORDER BY qt_visitas DESC;

-- G04 — Qual o status de cada pedido por rede e loja, com o atraso em relação à entrega prevista?
-- Atende: P3 (fluxo de pedidos e entregas)
SELECT ped.id_pedido, ped.dt_pedido, sm.nm_fantasia AS rede, lj.nm_loja, f.nm_fantasia AS fabricante,
       ped.tp_status_atual, ped.vl_preco_total, ped.dt_prevista_entrega,
       CASE WHEN ped.tp_status_atual NOT IN ('Entregue', 'Entregue Parcialmente', 'Cancelado', 'Recusado/Cortado')
             AND ped.dt_prevista_entrega < CURDATE() THEN 'ATRASADO' ELSE '' END AS alerta
FROM pedido ped
JOIN loja lj ON ped.id_loja = lj.id_loja
JOIN super_mercado sm ON ped.id_rede = sm.id_rede
JOIN fabricante f ON f.id_fabricante = ped.id_fabricante
ORDER BY ped.dt_pedido DESC;

-- G05 — Quais comissões foram apuradas por fabricante?
-- Atende: P4 (controle de contratos e comissões)
SELECT f.nm_fantasia AS fabricante, com.id_pedido, ped.dt_pedido, sm.nm_fantasia AS rede,
       com.valor_base, com.percentual_aplicado, com.valor_comissao, com.status_pagamento, com.dt_pagamento
FROM comissao com
JOIN contrato c ON com.id_contrato = c.id_contrato
JOIN fabricante f ON c.id_fabricante = f.id_fabricante
JOIN pedido ped ON ped.id_pedido = com.id_pedido
JOIN super_mercado sm ON sm.id_rede = ped.id_rede
ORDER BY f.nm_fantasia, ped.dt_pedido;

-- G06 — KPI "Índice de Perdas por Vencimento (IPV)": quantas unidades vencidas por loja em cada mês?
-- Atende: P1 (KPI 1 — IPV)
SELECT l.nm_loja, DATE_FORMAT(vp.dt_vencimento, '%Y-%m') AS mes,
       COUNT(*) AS qt_ocorrencias, SUM(vp.quantidade_produto_vencido) AS qt_unidades_vencidas
FROM vencimento_prod vp
JOIN loja l ON l.id_loja = vp.id_loja
GROUP BY l.nm_loja, DATE_FORMAT(vp.dt_vencimento, '%Y-%m')
ORDER BY mes, qt_unidades_vencidas DESC;

-- G07 — KPI "Taxa de pedidos por status": que percentual dos pedidos está em cada status?
-- Atende: P3 (KPI 2 — entregas integrais x parciais x cortadas)
SELECT tp_status_atual, COUNT(*) AS qt_pedidos, SUM(vl_preco_total) AS vl_total,
       ROUND(100 * COUNT(*) / (SELECT COUNT(*) FROM pedido), 2) AS pct_pedidos
FROM pedido
GROUP BY tp_status_atual
ORDER BY qt_pedidos DESC;

-- G08 — KPI "Comissões apuradas x liquidadas": quanto há por status de pagamento em cada fabricante?
-- Atende: P4 (KPI 3 — comissões apuradas x pagas)
SELECT f.nm_fantasia AS fabricante, com.status_pagamento,
       COUNT(*) AS qt_comissoes, SUM(com.valor_comissao) AS vl_comissao
FROM comissao com
JOIN contrato c ON c.id_contrato = com.id_contrato
JOIN fabricante f ON f.id_fabricante = c.id_fabricante
GROUP BY f.nm_fantasia, com.status_pagamento
ORDER BY f.nm_fantasia, com.status_pagamento;


-- A01 — Existe pedido registrado sem nenhum item?
-- Verifica: RN03 (todo pedido tem ao menos um item)
SELECT p.id_pedido, p.dt_pedido, p.tp_status_atual
FROM pedido p
LEFT JOIN item_pedido ip ON p.id_pedido = ip.id_pedido
WHERE ip.id_pedido IS NULL;

-- A02 — Existe lote com validade anterior ou igual à fabricação?
-- Verifica: RN07 (dt_validade > dt_fabricacao)
SELECT id_lote, numero_lote, dt_fabricacao, dt_validade
FROM lote
WHERE dt_validade <= dt_fabricacao;

-- A03 — Existe item vendido por preço diferente do de tabela?
-- Verifica: RN04 (preço negociado não pode ser inferior ao de tabela); lista também preços acima para conferência
SELECT ip.id_pedido, p.ds_produto, p.vl_preco_tabela, ip.vl_preco_negociado,
       (ip.vl_preco_negociado - p.vl_preco_tabela) AS diferenca,
       CASE WHEN ip.vl_preco_negociado < p.vl_preco_tabela
            THEN 'ABAIXO DA TABELA - viola RN04'
            ELSE 'ACIMA DA TABELA - conferir' END AS situacao
FROM item_pedido ip
JOIN produto p ON ip.id_produto = p.id_produto
WHERE ip.vl_preco_negociado <> p.vl_preco_tabela;

-- A04 — Existe loja ativa que nunca recebeu visita de promotor?
-- Verifica: P2 (cobertura das visitas); RN11 (toda loja ativa recebe visita)
SELECT l.id_loja, l.cd_loja_rede, l.nm_loja, sm.nm_fantasia AS rede
FROM loja l
JOIN super_mercado sm ON l.id_rede = sm.id_rede
LEFT JOIN visita v ON l.id_loja = v.id_loja
WHERE l.in_ativa = TRUE AND l.tp_loja = 'Loja' AND v.id_visita IS NULL;

-- A05 — Existem ocorrências de vencimento ainda pendentes de descarte físico?
-- Verifica: RN05 (produto vencido não pode ficar em gôndola nem ser comercializado)
SELECT vp.id_vencimento, l.nm_loja, vp.dt_vencimento, vp.quantidade_produto_vencido, vp.status_vencimento
FROM vencimento_prod vp
JOIN loja l ON vp.id_loja = l.id_loja
WHERE vp.status_vencimento IN ('Identificado', 'Notificado');

-- A06 — Existe pedido cuja rede é diferente da rede da loja de entrega?
-- Verifica: consistência do id_rede gravado em PEDIDO (cópia de LOJA.id_rede; ver README 1.4)
SELECT p.id_pedido, p.id_rede AS rede_do_pedido, l.id_rede AS rede_da_loja
FROM pedido p
JOIN loja l ON l.id_loja = p.id_loja
WHERE p.id_rede <> l.id_rede;

-- A07 — Existe pedido cujo valor total difere da soma dos itens?
-- Verifica: consistência de VL_PRECO_TOTAL (valor consolidado; ver README 1.4)
SELECT p.id_pedido, p.vl_preco_total,
       COALESCE(SUM(ip.qt_solicitada * ip.vl_preco_negociado), 0) AS soma_itens
FROM pedido p
LEFT JOIN item_pedido ip ON ip.id_pedido = p.id_pedido
GROUP BY p.id_pedido, p.vl_preco_total
HAVING p.vl_preco_total <> COALESCE(SUM(ip.qt_solicitada * ip.vl_preco_negociado), 0);

-- A08 — Existe loja ativa sem visita nos últimos 30 dias (ou nunca visitada)?
-- Verifica: RN11 (periodicidade mínima de visita; ajustar o intervalo ao valor definido na RN11)
SELECT l.id_loja, l.nm_loja, MAX(v.dt_visita) AS ultima_visita
FROM loja l
LEFT JOIN visita v ON v.id_loja = l.id_loja
WHERE l.in_ativa = TRUE AND l.tp_loja = 'Loja'
GROUP BY l.id_loja, l.nm_loja
HAVING MAX(v.dt_visita) IS NULL OR MAX(v.dt_visita) < DATE_SUB(CURDATE(), INTERVAL 30 DAY);

-- A09 — Existe item de pedido cujo produto é de outro fabricante?
-- Verifica: RN01 (o pedido é fechado com um fabricante; seus itens são produtos dele)
SELECT ip.id_pedido, ped.id_fabricante AS fabricante_do_pedido, p.id_fabricante AS fabricante_do_produto, p.ds_produto
FROM item_pedido ip
JOIN pedido ped ON ped.id_pedido = ip.id_pedido
JOIN produto p ON p.id_produto = ip.id_produto
WHERE p.id_fabricante <> ped.id_fabricante;

-- A10 — Existe comissão inconsistente com o pedido, o contrato ou a RN10?
-- Verifica: RN08 (comissão só de pedido entregue; cancelado gera comissão Cancelado) e RN10 (valor = base x percentual)
SELECT com.id_comissao, com.id_pedido, ped.tp_status_atual, com.status_pagamento,
       CASE
         WHEN c.id_fabricante <> ped.id_fabricante THEN 'contrato de outro fabricante'
         WHEN ped.tp_status_atual NOT IN ('Entregue', 'Entregue Parcialmente', 'Cancelado') THEN 'pedido nao entregue'
         WHEN ped.tp_status_atual = 'Cancelado' AND com.status_pagamento <> 'Cancelado' THEN 'pedido cancelado com comissao ativa'
         WHEN ABS(com.valor_comissao - ROUND(com.valor_base * com.percentual_aplicado / 100, 2)) > 0.01 THEN 'valor diferente de base x percentual'
       END AS problema
FROM comissao com
JOIN pedido ped ON ped.id_pedido = com.id_pedido
JOIN contrato c ON c.id_contrato = com.id_contrato
HAVING problema IS NOT NULL;

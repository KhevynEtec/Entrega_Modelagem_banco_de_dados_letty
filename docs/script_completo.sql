-- S01 — Catálogo de produtos com fabricante e lotes cadastrados
SELECT f.nm_fantasia AS fabricante, p.ds_produto, p.ean, p.vl_preco_tabela,
       lo.numero_lote, lo.dt_fabricacao, lo.dt_validade
FROM produto p
JOIN fabricante f ON f.id_fabricante = p.id_fabricante
LEFT JOIN lote lo ON lo.id_produto = p.id_produto
ORDER BY f.nm_fantasia, p.ds_produto, lo.dt_validade;

-- S02 — Lojas com rede, telefone e e-mail de recebimento
SELECT sm.nm_fantasia AS rede, l.cd_loja_rede, l.nm_loja, tl.telefone, el.email
FROM loja l
JOIN super_mercado sm ON sm.id_rede = l.id_rede
LEFT JOIN telefone_loja tl ON tl.id_loja = l.id_loja
LEFT JOIN email_loja el ON el.id_loja = l.id_loja
ORDER BY sm.nm_fantasia, l.cd_loja_rede;

